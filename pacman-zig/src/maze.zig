pub fn index(x: i32, y: i32) usize {
    return @intCast(y * width + x);
}

pub fn isWalkable(x: i32, y: i32) bool {
    if (x < 0 or x >= width or y < 0 or y >= height) return false;
    const tile = cells[index(x, y)];
    return tile == 0 or tile == 2;
}

pub fn isPortal(x: i32, y: i32) bool {
    // The historic map marks the horizontal tunnel as open path cells rather
    // than using TILE_PORTAL.  Give those two edge cells explicit semantics.
    return y == 14 and (x == 0 or x == width - 1);
}
